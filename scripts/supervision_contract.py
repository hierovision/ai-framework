#!/usr/bin/env python3
"""The shared supervision contract (RM-069).

The delegation observer reuses the watchdog's supervision semantics instead of
re-guessing thresholds in TypeScript. This module is the Python side of that
contract: it publishes the documented defaults and the predicates the plugin's
fixtures mirror, and it can regenerate/verify
`scripts/supervision_contract.json`.

Rules:
  * no new numbers here — every value is imported from its owner
    (`watch_agent` for stall/call/loop/generation, `observe_completion` for the
    wake deadline);
  * the JSON file is generated, never hand-edited; `--check` fails on drift;
  * the plugin's `state.test.ts` asserts its DEFAULTS equal the same file.

Usage:
  python3 scripts/supervision_contract.py --check
  python3 scripts/supervision_contract.py --write
"""
import argparse
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import watch_agent  # noqa: E402 - threshold owner

CONTRACT_PATH = os.path.join(HERE, "supervision_contract.json")


def _load_observer():
    path = os.path.join(HERE, "observe_completion.py")
    spec = importlib.util.spec_from_file_location("observe_completion", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def contract():
    """The contract payload, sourced from the owning modules."""
    return {
        "version": 1,
        "source": ("scripts/watch_agent.py + scripts/observe_completion.py "
                   "(generated by scripts/supervision_contract.py)"),
        "stall_seconds": watch_agent.DEFAULT_STALL_SECONDS,
        "call_seconds": watch_agent.DEFAULT_CALL_SECONDS,
        "loop_repeats": watch_agent.DEFAULT_LOOP_REPEATS,
        "generation_seconds": watch_agent.DEFAULT_GENERATION_SECONDS,
        "milestone_min_interval_seconds": 30,
        "terminal_wake_deadline_seconds": _load_observer().DEFAULT_DEADLINE,
        "statuses": ["running", "waiting", "warning", "failed", "completed"],
    }


def predicates():
    """Names of the predicates the plugin mirror must reproduce (not code).

    `busy` and `stall` are verdict lanes; `loop` is the analysis loop signal;
    `terminal` is the one shared completion predicate. The plugin implements
    the same semantics over event data — it never imports Python.
    """
    return {
        "busy": watch_agent.verdict,
        "stall": watch_agent.verdict,
        "loop": watch_agent.analyze_session,
        "terminal": watch_agent.has_terminal_result,
        "step_open": watch_agent.assistant_step_closed,
    }


def load():
    with open(CONTRACT_PATH, encoding="utf-8") as fh:
        return json.load(fh)


def check():
    want = contract()
    try:
        have = load()
    except (OSError, ValueError) as exc:
        return [f"contract file unreadable: {exc}"]
    if have != want:
        diffs = [f"{key}: file={have.get(key)!r} expected={value!r}"
                 for key, value in want.items() if have.get(key) != value]
        return ["supervision contract drift: " + "; ".join(diffs)]
    for name, fn in predicates().items():
        if not callable(fn):
            return [f"predicate {name} is not callable"]
    return []


def write():
    with open(CONTRACT_PATH, "w", encoding="utf-8") as fh:
        json.dump(contract(), fh, indent=2)
        fh.write("\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail when the JSON contract drifts from its owners")
    ap.add_argument("--write", action="store_true",
                    help="regenerate scripts/supervision_contract.json")
    ap.add_argument("--dump", action="store_true", help="print the contract")
    a = ap.parse_args(argv)
    if a.write:
        write()
        print(f"wrote {CONTRACT_PATH}")
    if a.dump:
        print(json.dumps(contract(), indent=2))
    errors = check() if (a.check or not (a.write or a.dump)) else []
    if errors:
        for error in errors:
            print(f"FAIL: {error}", file=sys.stderr)
        return 1
    if not (a.write or a.dump):
        print("OK: supervision contract matches its owners")
    return 0


if __name__ == "__main__":
    sys.exit(main())
